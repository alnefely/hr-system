<?php

use App\Models\Admin;
use Illuminate\Support\Facades\Broadcast;

/*
|--------------------------------------------------------------------------
| قنوات البث
|--------------------------------------------------------------------------
| التفويض هنا هو خط الدفاع: من غيره أي مشرف يقدر يشترك في قناة أي حد
| تاني ويشوف إشعاراته.
|
| كل مشرف له قناة خاصة برقمه بس — مافيش قنوات فروع مشتركة عشان
| مانفتحش باب إن مشرف يسمع إشعارات زملائه في نفس الفرع.
|
| ملاحظة مهمة: مسار broadcasting/auth بيشتغل على الـ guard الافتراضي
| (web)، والمشرفين عندنا على guard اسمه admin — فـ $user اللي بيوصل
| للـ callback بيبقى null دايماً والنتيجة 403.
| عشان كده بنجيب المشرف من الـ guard الصح بنفسنا بدل ما نعتمد على
| المُعامل اللي بيمرره الفريمورك.
*/

Broadcast::channel('admin.{adminId}', function ($user, int $adminId) {
    /** @var Admin|null $admin */
    $admin = auth('admin')->user();

    return $admin !== null && (int) $admin->id === $adminId;
});
